import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { distribution } from '../distribution.js';
const read = file => readFileSync(new URL(`../tools/sts-cli/${file}`, import.meta.url), 'utf8');
test('published STS catalog is npm-backed, not the retired executable entry', () => {
  const tool = JSON.parse(read('tool.json'));
  const release = JSON.parse(read('release.json'));
  assert.deepEqual(tool.distribution, { type: 'npm', package: '@muneris/sts-cli' });
  assert.match(tool.runtime, /Node.js 22/);
  assert.equal(tool.asset, undefined);
  assert.equal(release.url, 'https://www.npmjs.com/package/@muneris/sts-cli');
  assert.match(release.sourceCommit, /^[a-f0-9]{40}$/);
  const result = distribution(tool, release);
  assert.deepEqual(result.downloads, []);
  assert.equal(result.installation.command, release.install);
  assert.match(read('README.md'), /npm install --global @muneris\/sts-cli/);
  assert.doesNotMatch(read('README.md'), /\.NET 10|sts\.exe/);
  assert.ok(read('CHANGELOG.md').includes(`## ${release.version} - `));
});
